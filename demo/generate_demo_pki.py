#!/usr/bin/env python3
"""Generate the demo PKI (SRS §13.4). DEMO ONLY — never use these certificates or keys elsewhere.

- Demo Trusted Root: random P-256 key.
- Demo Root G3: random P-256 key. It is distrusted only by the scenario-a root-distrust feed (rule R3).
  (Decision A, docs/verification-log.md: a scalar-4 key would trip R4 at baseline, so the demo could
  never start VALID. R4 stays implemented and is unit-tested with a k=4 key.)
- One `localhost` server leaf under each root, for the partner-sim sidecar.

Writes:
  app/ledger-api/deploy/trust/extra-roots.pem     both roots (trusted via NODE_EXTRA_CA_CERTS)
  app/ledger-api/deploy/trust/excluded-spki.txt   empty (baseline)
  app/partner-sim/certs/*                         leaves + keys + README
  demo/feeds/scenario-a/root-distrust.json        distrust feed naming Demo Root G3

Root private keys are not written anywhere. Re-running replaces the PKI only with --force.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import sys
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

REPO = Path(__file__).resolve().parents[1]
TRUST = REPO / "app/ledger-api/deploy/trust"
CERTS = REPO / "app/partner-sim/certs"
FEED_A = REPO / "demo/feeds/scenario-a/root-distrust.json"
ORG = "Stale Demo PKI - NOT FOR PRODUCTION"

README = """# Demo-only certificates

These certificates and private keys were generated by `demo/generate_demo_pki.py` for the
Stale hackathon demo. They are **not secrets** and protect nothing:

- `leaf-trusted.*` is issued by *Demo Trusted Root* (random P-256 key).
- `leaf-g3.*` is issued by *Demo Root G3* (random P-256 key). In the demo, a root-distrust feed
  removes Demo Root G3 from trust, the way a root program removes a real CA.

They exist only so the `partner-sim` sidecar can serve TLS on `localhost:8443` / `localhost:8444`.
Never trust these roots outside this demo.
"""


def spki_sha256(cert: x509.Certificate) -> str:
    der = cert.public_key().public_bytes(serialization.Encoding.DER,
                                         serialization.PublicFormat.SubjectPublicKeyInfo)
    return hashlib.sha256(der).hexdigest()


def name(cn: str) -> x509.Name:
    return x509.Name([x509.NameAttribute(NameOID.ORGANIZATION_NAME, ORG),
                      x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def make_root(cn: str, key: ec.EllipticCurvePrivateKey, now: dt.datetime) -> x509.Certificate:
    pub = key.public_key()
    return (x509.CertificateBuilder()
            .subject_name(name(cn)).issuer_name(name(cn)).public_key(pub)
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - dt.timedelta(days=1)).not_valid_after(now + dt.timedelta(days=3650))
            .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
            .add_extension(x509.KeyUsage(digital_signature=False, content_commitment=False,
                                         key_encipherment=False, data_encipherment=False,
                                         key_agreement=False, key_cert_sign=True, crl_sign=True,
                                         encipher_only=False, decipher_only=False), critical=True)
            .add_extension(x509.SubjectKeyIdentifier.from_public_key(pub), critical=False)
            .sign(key, hashes.SHA256()))


def make_leaf(cn: str, root: x509.Certificate, root_key: ec.EllipticCurvePrivateKey,
              now: dt.datetime) -> tuple[x509.Certificate, ec.EllipticCurvePrivateKey]:
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder()
            .subject_name(name(cn)).issuer_name(root.subject).public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - dt.timedelta(days=1)).not_valid_after(now + dt.timedelta(days=365))
            .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .add_extension(x509.SubjectAlternativeName([x509.DNSName("localhost")]), critical=False)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
            .add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(root_key.public_key()),
                           critical=False)
            .sign(root_key, hashes.SHA256()))
    return cert, key


def pem(cert: x509.Certificate) -> bytes:
    return cert.public_bytes(serialization.Encoding.PEM)


def key_pem(key: ec.EllipticCurvePrivateKey) -> bytes:
    return key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                             serialization.NoEncryption())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="replace an existing demo PKI")
    args = ap.parse_args()
    if (TRUST / "extra-roots.pem").exists() and not args.force:
        print("demo PKI already exists (use --force to regenerate)", file=sys.stderr)
        return 1

    now = dt.datetime.now(dt.timezone.utc)
    trusted_key = ec.generate_private_key(ec.SECP256R1())
    g3_key = ec.generate_private_key(ec.SECP256R1())
    trusted = make_root("Demo Trusted Root", trusted_key, now)
    g3 = make_root("Demo Root G3", g3_key, now)
    leaf_t, leaf_t_key = make_leaf("localhost", trusted, trusted_key, now)
    leaf_g, leaf_g_key = make_leaf("localhost", g3, g3_key, now)

    TRUST.mkdir(parents=True, exist_ok=True)
    CERTS.mkdir(parents=True, exist_ok=True)
    (TRUST / "extra-roots.pem").write_bytes(pem(trusted) + pem(g3))
    (TRUST / "excluded-spki.txt").write_text("")
    for fname, data in {"leaf-trusted.pem": pem(leaf_t), "leaf-trusted.key": key_pem(leaf_t_key),
                        "leaf-g3.pem": pem(leaf_g), "leaf-g3.key": key_pem(leaf_g_key),
                        "demo-trusted-root.pem": pem(trusted), "demo-root-g3.pem": pem(g3)}.items():
        (CERTS / fname).write_bytes(data)
    (CERTS / "README.md").write_text(README)

    t_spki, g_spki = spki_sha256(trusted), spki_sha256(g3)
    FEED_A.parent.mkdir(parents=True, exist_ok=True)
    FEED_A.write_text(json.dumps({
        "schema": "stale.rootfeed/v1", "updated_at": "2026-10-24T00:00:00Z",
        "distrusted": [{"spki_sha256": g_spki, "subject": "CN=Demo Root G3",
                        "reason": "Root program removed this anchor from trust",
                        "source": "demo mirror of root-program action"}]}, indent=2) + "\n")

    print(f"Demo Trusted Root SPKI sha256: {t_spki}")
    print(f"Demo Root G3      SPKI sha256: {g_spki}")
    print(f"wrote {TRUST / 'extra-roots.pem'}, {CERTS}/, {FEED_A}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
